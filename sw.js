/* BOM-Genius Surveyor service worker: cache-first, network fallback, offline page, versioned cleanup */
const VERSION = 'v1.3.1';
const SHELL_CACHE = 'bomgenius-shell-' + VERSION;
const RUNTIME_CACHE = 'bomgenius-runtime-' + VERSION;
const CORE = ['./', 'index.html', 'offline.html', 'manifest.webmanifest', 'css/styles.css', 'js/app.js', 'favicon.svg', 'robots.txt'];
const OPTIONAL = [
  'icons/icon-72.png', 'icons/icon-96.png', 'icons/icon-128.png', 'icons/icon-144.png', 'icons/icon-152.png',
  'icons/icon-192.png', 'icons/icon-384.png', 'icons/icon-512.png', 'icons/icon-maskable-192.png',
  'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png', 'icons/favicon-16x16.png', 'icons/favicon-32x32.png',
  'screenshots/screenshot-wide.png', 'screenshots/screenshot-narrow.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await cache.addAll(CORE);
    // Icons are generated by the user later, so a missing file must not break install.
    await Promise.allSettled(OPTIONAL.map((u) => cache.add(u)));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keep = [SHELL_CACHE, RUNTIME_CACHE];
    const names = await caches.keys();
    await Promise.all(names.filter((n) => n.startsWith('bomgenius-') && !keep.includes(n)).map((n) => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;

  event.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: req.mode === 'navigate' });
    if (cached) {
      // refresh in background (stale-while-revalidate for runtime freshness)
      event.waitUntil(fetch(req).then(async (res) => {
        if (res && res.ok) {
          const c = await caches.open(CORE.some((p) => url.pathname.endsWith(p.replace('./', ''))) ? SHELL_CACHE : RUNTIME_CACHE);
          await c.put(req, res.clone());
        }
      }).catch(() => {}));
      return cached;
    }
    try {
      const res = await fetch(req);
      if (res && res.ok && res.type === 'basic') {
        const c = await caches.open(RUNTIME_CACHE);
        c.put(req, res.clone());
      }
      return res;
    } catch (err) {
      if (req.mode === 'navigate') {
        return (await caches.match('index.html')) || (await caches.match('offline.html')) || Response.error();
      }
      const fallback = await caches.match('offline.html');
      if (req.destination === 'document' && fallback) return fallback;
      return new Response('', { status: 504, statusText: 'Offline' });
    }
  })());
});
